USE DATABASE SKYPOINTS_DB;
USE SCHEMA TARGET;

CREATE OR REPLACE TABLE LATEST_MEMBERS AS
SELECT *
FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE_STAGING
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY MEMBER_ID
    ORDER BY LAST_FLIGHT_DATE DESC NULLS LAST
) = 1;

CREATE OR REPLACE TABLE TABLE_INDIA AS
SELECT * FROM LATEST_MEMBERS
WHERE UPPER(COUNTRY) = 'IND';

CREATE OR REPLACE TABLE TABLE_USA AS
SELECT * FROM LATEST_MEMBERS
WHERE UPPER(COUNTRY) = 'USA';

CREATE OR REPLACE TABLE TABLE_AUSTRALIA AS
SELECT * FROM LATEST_MEMBERS
WHERE UPPER(COUNTRY) IN ('AU','AUS');

SELECT MEMBER_ID, MEMBER_NAME, COUNTRY, LAST_FLIGHT_DATE
FROM LATEST_MEMBERS
ORDER BY MEMBER_ID;