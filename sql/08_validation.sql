USE DATABASE SKYPOINTS_DB;

-- 1. Mandatory fields
SELECT *
FROM RAW.MEMBER_PROFILE_RAW
WHERE MEMBER_ID IS NULL
   OR MEMBER_NAME IS NULL;

-- 2. Duplicate member IDs
SELECT MEMBER_ID, COUNT(*) AS CNT
FROM STAGING.MEMBER_PROFILE_STAGING
GROUP BY MEMBER_ID
HAVING COUNT(*) > 1;

-- 3. Stale members
SELECT MEMBER_ID, MEMBER_NAME, LAST_FLIGHT_DATE, STALE_MEMBER
FROM STAGING.MEMBER_PROFILE_STAGING
ORDER BY MEMBER_ID;

-- 4. Redemption validation
SELECT *
FROM REDEMPTION.REDEMPTION_FLAT
WHERE MILES_REDEEMED < 0
   OR STATUS NOT IN ('COMPLETED','PENDING');

-- 5. Final counts
SELECT 'RAW' AS LAYER, COUNT(*) AS CNT
FROM RAW.MEMBER_PROFILE_RAW
UNION ALL
SELECT 'STAGING', COUNT(*)
FROM STAGING.MEMBER_PROFILE_STAGING
UNION ALL
SELECT 'LATEST', COUNT(*)
FROM TARGET.LATEST_MEMBERS
UNION ALL
SELECT 'REDEMPTIONS', COUNT(*)
FROM REDEMPTION.REDEMPTION_FLAT;