USE DATABASE SKYPOINTS_DB;
USE SCHEMA STAGING;

CREATE OR REPLACE TABLE MEMBER_PROFILE_STAGING AS
WITH C AS (
    SELECT
        *,
        CASE
            WHEN SOURCE_FILE_NAME = 'AUS(Sheet1).csv'
                THEN TRY_TO_DATE(DOB_RAW, 'YYYY-MM-DD')
            WHEN SOURCE_FILE_NAME = 'IND(in).csv'
                THEN TRY_TO_DATE(DOB_RAW, 'MM/DD/YYYY')
        END AS DOB_DATE,

        CASE
            WHEN SOURCE_FILE_NAME = 'AUS(Sheet1).csv'
                THEN TRY_TO_DATE(ENROLLMENT_DATE_RAW, 'YYYY-MM-DD')
            WHEN SOURCE_FILE_NAME = 'IND(in).csv'
                THEN TRY_TO_DATE(ENROLLMENT_DATE_RAW, 'MM/DD/YYYY')
            WHEN SOURCE_FILE_NAME = 'USA(in).csv'
                THEN TRY_TO_DATE(LPAD(ENROLLMENT_DATE_RAW, 8, '0'), 'MMDDYYYY')
        END AS ENROLL_DATE,

        CASE
            WHEN SOURCE_FILE_NAME = 'AUS(Sheet1).csv'
                THEN TRY_TO_DATE(LAST_FLIGHT_DATE_RAW, 'YYYY-MM-DD')
            WHEN SOURCE_FILE_NAME = 'IND(in).csv'
                THEN TRY_TO_DATE(LAST_FLIGHT_DATE_RAW, 'MM/DD/YYYY')
            WHEN SOURCE_FILE_NAME = 'USA(in).csv'
                THEN TRY_TO_DATE(LPAD(LAST_FLIGHT_DATE_RAW, 8, '0'), 'MMDDYYYY')
        END AS FLIGHT_DATE
    FROM SKYPOINTS_DB.RAW.MEMBER_PROFILE_RAW
)
SELECT
    MEMBER_ID,
    MEMBER_NAME,
    ENROLL_DATE AS ENROLLMENT_DATE,
    FLIGHT_DATE AS LAST_FLIGHT_DATE,
    TIER_CODE,
    COUNTRY,
    DOB_DATE AS DOB,
    IS_ACTIVE,

    DATEDIFF(YEAR, DOB_DATE, CURRENT_DATE())
      - IFF(
          DATEADD(YEAR, DATEDIFF(YEAR, DOB_DATE, CURRENT_DATE()), DOB_DATE)
          > CURRENT_DATE(), 1, 0
        ) AS AGE,

    IFF(
        FLIGHT_DATE IS NOT NULL
        AND DATEDIFF(DAY, FLIGHT_DATE, CURRENT_DATE()) > 90,
        TRUE,
        FALSE
    ) AS STALE_MEMBER

FROM C;

SELECT * FROM MEMBER_PROFILE_STAGING;