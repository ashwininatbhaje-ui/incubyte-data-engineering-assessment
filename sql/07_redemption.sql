CREATE OR REPLACE TABLE REDEMPTION_FLAT AS
SELECT
    JSON_DATA:member_id::VARCHAR MEMBER_ID,
    TO_DATE(JSON_DATA:feed_date::VARCHAR,'YYYYMMDD') FEED_DATE,
    R.VALUE:txn_id::VARCHAR TXN_ID,
    TO_DATE(R.VALUE:txn_date::VARCHAR,'YYYYMMDD') TXN_DATE,
    R.VALUE:partner::VARCHAR PARTNER,
    R.VALUE:miles_redeemed::NUMBER MILES_REDEEMED,
    R.VALUE:status::VARCHAR STATUS
FROM REDEMPTION_RAW,
LATERAL FLATTEN(INPUT => JSON_DATA:redemptions) R;

SELECT * FROM REDEMPTION_FLAT;